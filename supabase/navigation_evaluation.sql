-- ---------------------------------------------------------------------------
-- 4. Views — one row per trip, and a per-mode summary
-- ---------------------------------------------------------------------------
-- security_invoker: the views apply the caller's RLS (admins only).
create or replace view public.navigation_trip_metrics
with (security_invoker = true) as
select
  s.trip_id,
  s.mode,
  s.user_id,
  s.visitor_session_id,
  s.from_name,
  s.to_name,
  s.distance_meters,
  s.started_at,
  e.completed_at,
  e.duration_seconds,
  coalesce(e.completed, false)                        as completed,
  coalesce(e.completed and e.completed_manually, false) as completed_manually,
  case
    when e.trip_id is null                            then 'no_end_row'
    when e.completed and not coalesce(e.completed_manually, false)
                                                      then 'arrived'
    when e.completed                                  then 'arrived_manual'
    else                                                   'abandoned'
  end                                                 as outcome,
  e.error_count,
  e.reroute_count,
  coalesce(e.total_steps, s.total_steps)              as total_steps,
  coalesce(e.off_route_tracked, false)                as off_route_tracked,
  case
    when coalesce(e.off_route_tracked, false)
     and coalesce(e.total_steps, s.total_steps) > 0
    then e.error_count::numeric / coalesce(e.total_steps, s.total_steps)
  end                                                 as error_rate,
  -- Last, so "create or replace view" can add it to the existing view.
  s.device_code
from public.navigation_sessions s
left join lateral (
  select *
  from public.navigation_sessions x
  where x.trip_id = s.trip_id and x.row_type = 'end'
  order by x.id desc
  limit 1
) e on true
where s.row_type = 'start' and s.trip_id is not null;

create or replace view public.navigation_evaluation_summary
with (security_invoker = true) as
select
  mode,
  count(*)                                                   as trips,
  count(*) filter (where completed)                          as completed_trips,
  count(*) filter (where completed and not completed_manually)
                                                             as completed_by_gps,
  count(*) filter (where completed_manually)                 as completed_manually,
  round(avg(case when completed then 1.0 else 0 end), 4)     as task_success_rate,
  round(avg(case when completed and not completed_manually
                 then 1.0 else 0 end), 4)                    as task_success_rate_gps_only,
  round(avg(duration_seconds) filter (where completed), 1)   as avg_completion_seconds,
  round(avg(error_rate) filter (where off_route_tracked), 4) as mean_error_rate,
  sum(error_count) filter (where off_route_tracked)          as total_errors,
  sum(total_steps) filter (where off_route_tracked)          as total_steps_tracked,
  sum(reroute_count)                                         as total_reroutes
from public.navigation_trip_metrics
group by mode;

