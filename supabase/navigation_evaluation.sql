-- ============================================================================
-- UM-AR Nav — evaluation data (thesis objective 4)
--
-- Adds the columns the user app writes for route completion time, task
-- success, navigation error rate and the SUS ↔ trip link, insert-only RLS
-- for the app, and two views that compute the metrics.
--
-- Safe to run more than once. NOT run automatically — paste it into the
-- Supabase SQL editor. The app keeps working before it is run: unknown
-- columns are dropped from inserts (and logged) until they exist.
--
-- How the app writes navigation_sessions (one trip = rows sharing trip_id):
--   row_type 'start' — when guidance starts
--   row_type 'end'   — once: arrived (completed = true) or left without
--                      arriving (completed = false), with duration_seconds,
--                      error_count, reroute_count, total_steps,
--                      completed_manually, off_route_tracked
--   A 'start' row with no 'end' row = the app was closed / killed mid-trip.
--   Both rows carry device_code.
--
-- device_code (navigation_sessions and sus_responses): a random UUID made once
-- per app install and kept on the device. It is not derived from the hardware,
-- a name, an email or a location, so it says nothing about the person.
--
-- Metric definitions:
--   task success           = completed (arrived), split by completed_manually
--                            (user pressed "I have arrived" / tapped through in
--                            2D without a GPS confirmation)
--   route completion time  = duration_seconds of completed trips
--   navigation error rate  = error_count / total_steps
--                            error_count = separate off-route events (GPS more
--                            than 25 m from the route, 5 m hysteresis, fixes
--                            worse than 30 m accuracy ignored) + reroutes.
--                            A reroute follows an off-route event, so one
--                            deviation that is rerouted counts as 2. For
--                            off-route events alone use
--                            error_count - reroute_count. Rows logged before
--                            this change hold off-route events only.
--                            total_steps = turn-by-turn steps of the planned
--                            route (outdoor + indoor)
--                            Only meaningful when off_route_tracked = true.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. navigation_sessions
-- ---------------------------------------------------------------------------
-- Created only if it doesn't exist yet (it already exists if the app has
-- logged trips before). Base columns match what the app has always sent.
create table if not exists public.navigation_sessions (
  id                 bigint generated by default as identity primary key,
  user_id            uuid,
  visitor_session_id uuid,
  from_node          text,
  to_node            text,
  from_name          text,
  to_name            text,
  distance_meters    double precision,
  duration_seconds   integer,
  completed          boolean not null default false,
  started_at         timestamptz default now(),
  completed_at       timestamptz,
  created_at         timestamptz default now()
);

alter table public.navigation_sessions
  add column if not exists trip_id            uuid,
  add column if not exists row_type           text,
  add column if not exists mode               text,
  add column if not exists completed_manually boolean default false,
  add column if not exists error_count        integer,
  add column if not exists reroute_count      integer,
  add column if not exists total_steps        integer,
  add column if not exists off_route_tracked  boolean,
  add column if not exists device_code        text;

-- Value checks (added separately so re-running doesn't fail).
do $$
begin
  if not exists (select 1 from pg_constraint
                 where conname = 'navigation_sessions_row_type_check') then
    alter table public.navigation_sessions
      add constraint navigation_sessions_row_type_check
      check (row_type is null or row_type in ('start', 'end'));
  end if;
  if not exists (select 1 from pg_constraint
                 where conname = 'navigation_sessions_mode_check') then
    alter table public.navigation_sessions
      add constraint navigation_sessions_mode_check
      check (mode is null or mode in ('2d', 'ar'));
  end if;
  if not exists (select 1 from pg_constraint
                 where conname = 'navigation_sessions_counts_check') then
    alter table public.navigation_sessions
      add constraint navigation_sessions_counts_check
      check (coalesce(error_count, 0) >= 0
         and coalesce(reroute_count, 0) >= 0
         and coalesce(total_steps, 0) >= 0);
  end if;
end $$;

create index if not exists navigation_sessions_trip_id_idx
  on public.navigation_sessions (trip_id);

-- ---------------------------------------------------------------------------
-- 2. sus_responses
-- ---------------------------------------------------------------------------
create table if not exists public.sus_responses (
  id                 bigint generated by default as identity primary key,
  user_id            uuid,
  visitor_session_id uuid,
  user_type          text,
  q1 smallint, q2 smallint, q3 smallint, q4 smallint, q5 smallint,
  q6 smallint, q7 smallint, q8 smallint, q9 smallint, q10 smallint,
  sus_score          numeric,
  comment            text,
  submitted_at       timestamptz default now()
);

-- The trip the survey followed = navigation_sessions.trip_id.
alter table public.sus_responses
  add column if not exists navigation_session_id uuid,
  add column if not exists device_code           text;

create index if not exists sus_responses_navigation_session_id_idx
  on public.sus_responses (navigation_session_id);
create index if not exists sus_responses_device_code_idx
  on public.sus_responses (device_code);

-- ---------------------------------------------------------------------------
-- 3. RLS — the app may only INSERT (no read, update or delete)
-- ---------------------------------------------------------------------------
-- Visitors use the anon key (user_id must be null); signed-in users may only
-- write rows for themselves. Admins (user_profiles.role = 'admin', as in the
-- admin app) may read.
alter table public.navigation_sessions enable row level security;
alter table public.sus_responses       enable row level security;

drop policy if exists "app insert navigation_sessions" on public.navigation_sessions;
create policy "app insert navigation_sessions"
  on public.navigation_sessions for insert
  to anon, authenticated
  with check (user_id is null or user_id = auth.uid());

drop policy if exists "app insert sus_responses" on public.sus_responses;
create policy "app insert sus_responses"
  on public.sus_responses for insert
  to anon, authenticated
  with check (user_id is null or user_id = auth.uid());

drop policy if exists "admin read navigation_sessions" on public.navigation_sessions;
create policy "admin read navigation_sessions"
  on public.navigation_sessions for select
  to authenticated
  using (exists (select 1 from public.user_profiles p
                 where p.id = auth.uid()
                   and p.role = 'admin'
                   and coalesce(p.is_active, true)));

drop policy if exists "admin read sus_responses" on public.sus_responses;
create policy "admin read sus_responses"
  on public.sus_responses for select
  to authenticated
  using (exists (select 1 from public.user_profiles p
                 where p.id = auth.uid()
                   and p.role = 'admin'
                   and coalesce(p.is_active, true)));

